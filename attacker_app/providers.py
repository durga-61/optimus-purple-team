"""LLM Provider abstraction and implementations for Part 2 AI Attacker Application.

Supports:
- OpenAI (via HTTP chat completions)
- Anthropic (via HTTP messages)
- MockLLMProvider (for offline testing and evaluation)
- Deterministic fallback when no provider or key is configured

Zero imports from Part 1. All network communication isolated.
"""

import abc
import logging
from typing import Callable, Optional
import httpx

from attacker_app.config import config

logger = logging.getLogger("attacker.providers")


class LLMProviderError(Exception):
    """Exception raised when an LLM provider encounters an error."""
    pass


class LLMProvider(abc.ABC):
    """Abstract interface for LLM completion providers."""

    @property
    @abc.abstractmethod
    def provider_name(self) -> str:
        """Name of the provider service."""
        pass

    @property
    @abc.abstractmethod
    def model_name(self) -> str:
        """Configured model name."""
        pass

    @abc.abstractmethod
    def generate(self, prompt: str, system_prompt: str) -> str:
        """Generate raw text response from the provider given prompt and system instructions.

        Returns:
            Raw string generated by the LLM.
        """
        pass


class OpenAIProvider(LLMProvider):
    """OpenAI API provider via direct HTTP requests."""

    def __init__(self, api_key: Optional[str] = None, model: Optional[str] = None):
        self.api_key = api_key or config.OPENAI_API_KEY
        self.model = model or config.ATTACKER_LLM_MODEL or "gpt-4o-mini"
        self.endpoint = "https://api.openai.com/v1/chat/completions"

    @property
    def provider_name(self) -> str:
        return "OpenAI"

    @property
    def model_name(self) -> str:
        return self.model

    def generate(self, prompt: str, system_prompt: str) -> str:
        if not self.api_key:
            raise LLMProviderError("OpenAI API key is missing or unconfigured.")

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": prompt},
            ],
            "temperature": 0.2,
        }

        try:
            with httpx.Client(timeout=config.REQUEST_TIMEOUT) as client:
                res = client.post(self.endpoint, headers=headers, json=payload)
                if res.status_code != 200:
                    raise LLMProviderError(
                        f"OpenAI API returned HTTP {res.status_code}: {res.text}"
                    )
                data = res.json()
                return data["choices"][0]["message"]["content"]
        except httpx.RequestError as exc:
            raise LLMProviderError(f"Network error connecting to OpenAI: {exc}") from exc


class AnthropicProvider(LLMProvider):
    """Anthropic API provider via direct HTTP requests."""

    def __init__(self, api_key: Optional[str] = None, model: Optional[str] = None):
        self.api_key = api_key or config.ANTHROPIC_API_KEY
        self.model = model or config.ATTACKER_LLM_MODEL or "claude-3-5-sonnet-20241022"
        self.endpoint = "https://api.anthropic.com/v1/messages"

    @property
    def provider_name(self) -> str:
        return "Anthropic"

    @property
    def model_name(self) -> str:
        return self.model

    def generate(self, prompt: str, system_prompt: str) -> str:
        if not self.api_key:
            raise LLMProviderError("Anthropic API key is missing or unconfigured.")

        headers = {
            "x-api-key": self.api_key,
            "anthropic-version": "2023-06-01",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.model,
            "system": system_prompt,
            "messages": [
                {"role": "user", "content": prompt},
            ],
            "max_tokens": 1024,
            "temperature": 0.2,
        }

        try:
            with httpx.Client(timeout=config.REQUEST_TIMEOUT) as client:
                res = client.post(self.endpoint, headers=headers, json=payload)
                if res.status_code != 200:
                    raise LLMProviderError(
                        f"Anthropic API returned HTTP {res.status_code}: {res.text}"
                    )
                data = res.json()
                return data["content"][0]["text"]
        except httpx.RequestError as exc:
            raise LLMProviderError(f"Network error connecting to Anthropic: {exc}") from exc


class MockLLMProvider(LLMProvider):
    """Mock LLM provider for testing, offline evaluation, and edge-case simulation."""

    def __init__(self, response_generator: Optional[Callable[[str], str]] = None, model: str = "mock-model"):
        self.response_generator = response_generator
        self.model = model
        self.last_prompt: Optional[str] = None
        self.last_system_prompt: Optional[str] = None

    @property
    def provider_name(self) -> str:
        return "MockLLM"

    @property
    def model_name(self) -> str:
        return self.model

    def set_response(self, text: str) -> None:
        """Configure provider to return fixed text."""
        self.response_generator = lambda _: text

    def generate(self, prompt: str, system_prompt: str) -> str:
        self.last_prompt = prompt
        self.last_system_prompt = system_prompt
        if self.response_generator:
            return self.response_generator(prompt)
        return (
            '{"strategy_rationale": "Mock generated rationale", '
            '"attack_type": "capacity_manipulation", '
            '"target": "free_capacity", '
            '"value": 45.0, '
            '"objective": "Mock capacity manipulation attack"}'
        )


def get_llm_provider(name: Optional[str] = None) -> Optional[LLMProvider]:
    """Factory to retrieve configured LLM provider instance."""
    provider_type = (name or config.ATTACKER_LLM_PROVIDER).lower()

    if provider_type == "mock":
        return MockLLMProvider()

    if provider_type == "anthropic":
        if config.ANTHROPIC_API_KEY:
            return AnthropicProvider()
        return None

    if provider_type == "openai":
        if config.OPENAI_API_KEY:
            return OpenAIProvider()
        return None

    return None
